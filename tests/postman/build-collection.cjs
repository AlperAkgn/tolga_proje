function phase(name, description) {
  const group = { name, description, item: [] };
  phases.push(group);
  return group;
}
function script(listen, code) {
  return { listen, script: { type: "text/javascript", exec: code.trim().split("\n") } };
}
function add(group, name, method, route, expected, options = {}) {
  const header = [{ key: "Accept", value: "application/json" }, ...(options.headers || [])];
  if (options.csrf) header.push({ key: "X-AF-CSRF", value: options.csrf === true ? "{{csrfToken}}" : options.csrf });
  const request = { method, header, url: `{{baseUrl}}${route}`, description: options.description || name };
  const pre = [];
  if (options.json) {
    header.push({ key: "Content-Type", value: "application/json" });
    request.body = { mode: "raw", raw: "{{afRequestBody}}", options: { raw: { language: "json" } } };
    pre.push(`pm.variables.set('afRequestBody', JSON.stringify(${options.json}));`);
  }
  if (options.form) request.body = { mode: "formdata", formdata: options.form };
  if (options.pre) pre.push(options.pre);
  const tests = Array.isArray(expected)
    ? [`pm.test('HTTP ${expected.join(' or ')}', () => pm.expect(pm.response.code).to.be.oneOf(${JSON.stringify(expected)}));`]
    : [`pm.test('HTTP ${expected}', () => pm.response.to.have.status(${expected}));`];
  if (options.test) tests.push(options.test);
  const item = { name: `${String(++number).padStart(2, "0")} — ${name}`, request, event: [] };
  if (pre.length) item.event.push(script("prerequest", pre.join("\n")));
  item.event.push(script("test", tests.join("\n")));
  group.item.push(item);
}
function get(group, name, route, expected = 200, options) { add(group, name, "GET", route, expected, options); }
function csrf(group, name = "CSRF token") {
  get(group, name, "/api/auth/csrf", 200, { test: `
    pm.test('Request token is present', () => pm.expect(pm.response.json().requestToken).to.be.a('string').and.not.empty);
    if (pm.response.code === 200) pm.environment.set('csrfToken', pm.response.json().requestToken);
  ` });
}
function credentials(account, wrong = false) {
  return `{ userName: pm.environment.get('userName${account}'), password: ${wrong ? "'deliberately-wrong-password-qa9'" : `pm.environment.get('password${account}')`} }`;
}
function login(group, account) {
  csrf(group, `${account}: login CSRF`);
  add(group, `${account}: successful login`, "POST", "/api/auth/login", 200, {
    csrf: true, json: credentials(account), test: `
      if (pm.response.code === 200) pm.environment.set('artistId${account}', pm.response.json().id);
      pm.test('The signed-in artist is ${account}', () => pm.expect(pm.response.json().userName).to.eql(pm.environment.get('userName${account}')));
      pm.test('Session cookie is HttpOnly, Lax and scoped to /', () => {
        const cookie = pm.response.headers.all().filter(h => h.key.toLowerCase() === 'set-cookie').map(h => h.value).find(v => v.startsWith('afterform.artist='));
        pm.expect(cookie).to.be.a('string');
        pm.expect(cookie.toLowerCase()).to.include('httponly').and.include('samesite=lax').and.include('path=/');
      });
      pm.test('Login does not return password or hash', () => {
        const body = pm.response.json();
        pm.expect(body).not.to.have.property('password');
        pm.expect(body).not.to.have.property('passwordHash');
      });
    `
  });
  csrf(group, `${account}: authenticated CSRF`);
}
function logout(group, name = "Sign out") {
  csrf(group, "Current session CSRF");
  add(group, name, "POST", "/api/auth/logout", 204, { csrf: true });
  get(group, "Session after logout", "/api/auth/me", 401);
}
function text(key, value) { return { key, value, type: "text" }; }
function file(src = "{{validFile}}", key = "audioFile") { return { key, type: "file", src }; }
function form(account, changes = {}) {
  return [text("trackTitle", changes.title ?? `{{trackTitle${account}}}`), text("genre", changes.genre ?? "Electronic"),
    text("artistNote", changes.note ?? "QA9: synthetic audio; <strong>plain text note</strong>"),
    text("rightsConfirmation", changes.rights ?? "true"), ...(changes.files ?? [file(changes.src)])];
}
function upload(group, name, account, expected, options = {}) {
  add(group, name, "POST", "/api/demos", expected, {
    csrf: options.noCsrf ? false : true, form: options.form || form(account, options), test: options.test,
    description: "Local synthetic fixture only. Content-Type is generated by Postman. Invalid attempts also count toward the upload limit."
  });
}
function ownedList(account, count) { return `
  const body = pm.response.json();
  pm.test('List and rows belong to ${account}', () => {
    pm.expect(body.artistId).to.eql(pm.environment.get('artistId${account}'));
    pm.expect(body.items).to.be.an('array');
    body.items.forEach(d => pm.expect(d.artistId).to.eql(body.artistId));
  });
  ${count !== undefined ? `pm.test('Fresh ${account} fixture has ${count} demos', () => { pm.expect(body.summary.total).to.eql(${count}); pm.expect(body.totalCount).to.eql(${count}); });` : ""}
`; }
function saved(account, key) { return `
  if (pm.response.code === 201) pm.environment.set('${key}', String(pm.response.json().id));
  pm.test('Ownership comes from the session and initial status is Submitted', () => {
    const d = pm.response.json();
    pm.expect(d.artistId).to.eql(pm.environment.get('artistId${account}'));
    pm.expect(d.status).to.eql('Submitted');
    pm.expect(d.fileSha256.toLowerCase()).to.eql(pm.environment.get('fileSha256'));
    pm.expect(d.fileSizeBytes).to.eql(Number(pm.environment.get('fileSizeBytes')));
    pm.expect(d.submittedAtUtc).to.match(/Z$/);
    pm.expect(d).not.to.have.property('storageKey');
  });
`; }
